#!/usr/bin/env node
/**
 * Offline Mock TeX & dvisvgm simulator for LaTeX Vault.
 *
 * Used by `npm test` (and optionally in Obsidian Settings -> Binary paths)
 * to exercise LatexRenderer end-to-end without requiring a TeX installation.
 *
 * Directives supported inside comments in `main.tex`:
 *   % MOCK_DELAY_MS=<ms>   Sleep before completing compilation
 *   % MOCK_FAIL_PDF        Fail when compiling/converting PDF (DVI succeeds)
 *   % MOCK_FAIL_ALL        Always fail with a sample LaTeX error log
 *   % MOCK_BLANK_PDF       Emit an all-transparent SVG (with clipPath) for PDF
 *   % MOCK_RERUN           Emit a nicematrix rerun warning on pass 1, clean on pass 2
 */
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const cwd = process.cwd();

if (args.includes("--version")) {
  if (process.env.MOCK_MIKTEX === "1") {
    console.log("MiKTeX-pdfTeX 4.20 (MiKTeX 24.4)");
  } else {
    console.log("pdfTeX 3.141592653-2.6-1.40.26 (TeX Live 2024)");
  }
  process.exit(0);
}

const traceFile = process.env.MOCK_TRACE_FILE;
function trace(event) {
  if (traceFile) {
    appendFileSync(traceFile, `${JSON.stringify({ ...event, ts: Date.now() })}\n`, "utf8");
  }
}

const isDvisvgm =
  args.includes("--no-fonts=1") ||
  args.includes("main.pdf") ||
  args.includes("main.dvi");

if (isDvisvgm) {
  const isPdf = args.includes("--pdf");
  const inputFile = isPdf ? "main.pdf" : "main.dvi";
  const inputPath = join(cwd, inputFile);
  trace({ tool: "dvisvgm", mode: isPdf ? "pdf" : "dvi", args });

  if (!existsSync(inputPath)) {
    console.error(`dvisvgm: input file not found: ${inputFile}`);
    process.exit(1);
  }
  const meta = readFileSync(inputPath, "utf8");
  if (isPdf && meta.includes("BLANK_PDF")) {
    writeFileSync(
      join(cwd, "main.svg"),
      `<?xml version='1.0' encoding='UTF-8'?>\n` +
        `<svg xmlns='http://www.w3.org/2000/svg' width='100pt' height='50pt' viewBox='0 0 100 50'>\n` +
        `<defs><clipPath id='clip0'><path d='M0 0H100V50H0Z'/></clipPath></defs>\n` +
        `<g id='page1' clip-path='url(#clip0)'>\n` +
        `<path stroke='#000' stroke-opacity='0' fill='none' d='M0 0L50 50'/>\n` +
        `</g></svg>\n`,
      "utf8"
    );
    process.exit(0);
  }

  const label = isPdf ? "pdf" : "dvi";
  const passMarker = meta.includes("PASS2") ? "pass2" : "pass1";
  writeFileSync(
    join(cwd, "main.svg"),
    `<?xml version='1.0' encoding='UTF-8'?>\n` +
      `<!-- This file was generated by mock-dvisvgm (${label}, ${passMarker}) -->\n` +
      `<svg xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink' width='100pt' height='50pt' viewBox='0 0 100 50' data-engine='${label}' data-pass='${passMarker}'>\n` +
      `<defs><path id='g0-65' d='M1 1L9 9'/></defs>\n` +
      `<g id='page1'><use xlink:href='#g0-65'/><path stroke='#000' fill='none' d='M0 0L100 50'/></g>\n` +
      `</svg>\n`,
    "utf8"
  );
  process.exit(0);
}

// Invoked as latex / pdflatex
const texPath = join(cwd, "main.tex");
if (!existsSync(texPath)) {
  console.error("latex: main.tex not found");
  process.exit(1);
}

const tex = readFileSync(texPath, "utf8");
const delayMatch = tex.match(/%\s*MOCK_DELAY_MS=(\d+)/);
const delayMs = delayMatch ? Number(delayMatch[1]) : 0;

trace({ tool: "latex", event: "start", args });

function finishLatex() {
  if (tex.includes("MOCK_FAIL_ALL")) {
    writeFileSync(
      join(cwd, "main.log"),
      "This is pdfTeX (mock)\n! Undefined control sequence.\nl.4 \\notacommand\n",
      "utf8"
    );
    trace({ tool: "latex", event: "fail" });
    console.log("! Undefined control sequence.");
    process.exit(1);
  }

  const passFile = join(cwd, ".mock-pass");
  const pass = existsSync(passFile) ? Number(readFileSync(passFile, "utf8")) + 1 : 1;
  writeFileSync(passFile, String(pass), "utf8");

  if (tex.includes("MOCK_FAIL_PDF") && pass === 1) {
    writeFileSync(
      join(cwd, "main.log"),
      "This is pdfTeX (mock)\n! Package pgf Error: PDF mode failed.\n",
      "utf8"
    );
    trace({ tool: "latex", event: "fail-pdf" });
    process.exit(1);
  }

  const markers = [`PASS${pass}`];
  if (tex.includes("MOCK_BLANK_PDF")) markers.push("BLANK_PDF");
  writeFileSync(join(cwd, "main.pdf"), markers.join("\n"), "utf8");
  writeFileSync(join(cwd, "main.dvi"), markers.join("\n"), "utf8");

  if (tex.includes("MOCK_RERUN") && pass === 1) {
    writeFileSync(
      join(cwd, "main.log"),
      "This is pdfTeX (mock)\nPackage nicematrix Warning: Rerun to get the layout right.\n",
      "utf8"
    );
  } else {
    writeFileSync(join(cwd, "main.log"), "This is pdfTeX (mock)\nOutput written.\n", "utf8");
  }

  trace({ tool: "latex", event: "end", pass });
  process.exit(0);
}

if (delayMs > 0) {
  setTimeout(finishLatex, delayMs);
} else {
  finishLatex();
}
